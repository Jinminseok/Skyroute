-- 21. 예약 (BOOKING)
CREATE TABLE BOOKING (
    booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_no VARCHAR2(20) NOT NULL UNIQUE,
    member_id NUMBER NOT NULL,
    trip_type VARCHAR2(10) NOT NULL CHECK (trip_type IN ('ONEWAY', 'ROUNDTRIP')),
    outbound_flight_id NUMBER NOT NULL,
    inbound_flight_id NUMBER,
    status VARCHAR2(10) DEFAULT 'PENDING' NOT NULL CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'FAILED')),
    total_amount NUMBER(12) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    cancelled_at TIMESTAMP,
    CONSTRAINT fk_booking_member FOREIGN KEY (member_id) REFERENCES MEMBER(member_id),
    CONSTRAINT fk_booking_outbound FOREIGN KEY (outbound_flight_id) REFERENCES FLIGHT(flight_id),
    CONSTRAINT fk_booking_inbound FOREIGN KEY (inbound_flight_id) REFERENCES FLIGHT(flight_id),
    CONSTRAINT chk_booking_trip_type CHECK (
        (trip_type = 'ONEWAY' AND inbound_flight_id IS NULL) OR 
        (trip_type = 'ROUNDTRIP' AND inbound_flight_id IS NOT NULL)
    )
);

-- 22. 동승자 (BOOKING_PASSENGER)
