    booking_passenger_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id NUMBER NOT NULL,
    saved_passenger_id NUMBER,
    name VARCHAR2(50) NOT NULL,
    birth_date DATE NOT NULL,
    phone VARCHAR2(20),
    gender CHAR(1) CHECK (gender IN ('M', 'F')),
    passport_no VARCHAR2(20),
    passport_expiry DATE,
    CONSTRAINT fk_bk_pass_booking FOREIGN KEY (booking_id) REFERENCES BOOKING(booking_id),
    CONSTRAINT fk_bk_pass_saved FOREIGN KEY (saved_passenger_id) REFERENCES SAVED_PASSENGER(saved_passenger_id)
);

-- 23. 티켓 (TICKET)
CREATE TABLE TICKET (
    ticket_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id NUMBER NOT NULL,
    booking_passenger_id NUMBER NOT NULL,
    flight_id NUMBER NOT NULL,
    seat_id NUMBER NOT NULL,
    leg_type VARCHAR2(10) NOT NULL CHECK (leg_type IN ('OUTBOUND', 'INBOUND')),
    fare_amount NUMBER(10) NOT NULL,
    hold_status VARCHAR2(10) DEFAULT 'HOLDING' NOT NULL 
        CHECK (hold_status IN ('HOLDING', 'CONFIRMED', 'RELEASED', 'CANCELLED')),
    held_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    expired_at TIMESTAMP,
    checkin_status VARCHAR2(15) DEFAULT 'NOT_CHECKED_IN' NOT NULL 
        CHECK (checkin_status IN ('NOT_CHECKED_IN', 'CHECKED_IN', 'BOARDED', 'NO_SHOW')),
    checked_in_at TIMESTAMP,
    checked_in_by NUMBER,
    boarded_at TIMESTAMP,
    boarded_by NUMBER,
    CONSTRAINT fk_ticket_booking FOREIGN KEY (booking_id) REFERENCES BOOKING(booking_id),
    CONSTRAINT fk_ticket_bk_pass FOREIGN KEY (booking_passenger_id) REFERENCES BOOKING_PASSENGER(booking_passenger_id),
    CONSTRAINT fk_ticket_flight FOREIGN KEY (flight_id) REFERENCES FLIGHT(flight_id),
    CONSTRAINT fk_ticket_seat FOREIGN KEY (seat_id) REFERENCES SEAT(seat_id),
    CONSTRAINT fk_ticket_chk_staff FOREIGN KEY (checked_in_by) REFERENCES MEMBER(member_id),
    CONSTRAINT fk_ticket_brd_staff FOREIGN KEY (boarded_by) REFERENCES MEMBER(member_id)
);

-- 24. 결제 (PAYMENT)
