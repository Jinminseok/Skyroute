-- 2. 권역 (REGION)
CREATE TABLE REGION (
    region_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_name VARCHAR2(50) NOT NULL UNIQUE,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N'))
);

-- 3. 게이트 구역 (GATE_AREA)
CREATE TABLE GATE_AREA (
    gate_area_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_name VARCHAR2(50) NOT NULL UNIQUE,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N'))
);

-- 4. 노선 유형 (ROUTE_TYPE)
CREATE TABLE ROUTE_TYPE (
    route_type_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR2(50) NOT NULL UNIQUE,
    route_price NUMBER NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N'))
);

-- 5. 좌석 등급 (SEAT_CLASS)
-- ROWS, COLUMNS는 오라클 예약어이므로 쌍따옴표(") 처리하여 컬럼명으로 명시
CREATE TABLE SEAT_CLASS (
    seat_class_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name VARCHAR2(50) NOT NULL UNIQUE,
    class_ratio NUMBER(4,2) DEFAULT 1.0 NOT NULL CHECK (class_ratio > 0), --추가
    sort_order NUMBER(3) NOT NULL UNIQUE
);

-- 6. 시즌 (SEASON)
CREATE TABLE SEASON (
    season_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_name VARCHAR2(50) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    season_ratio NUMBER NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT chk_season_dates CHECK (end_date >= start_date)
);

-- 7. 알림 (NOTIFICATION)
CREATE TABLE NOTIFICATION (
    notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    type VARCHAR2(30) NOT NULL,
    content VARCHAR2(500) NOT NULL,
    ref_type VARCHAR2(20),
    ref_url VARCHAR2(100),
    is_read CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_read IN ('Y', 'N')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_notification_member FOREIGN KEY (member_id) REFERENCES MEMBER(member_id)
);


