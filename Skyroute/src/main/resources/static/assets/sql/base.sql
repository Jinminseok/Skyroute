-- 8. 공항 (AIRPORT)
CREATE TABLE AIRPORT (
    airport_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iata_code CHAR(3) NOT NULL UNIQUE,
    airport_name VARCHAR2(100) NOT NULL,
    country VARCHAR2(50) NOT NULL,
    timezone VARCHAR2(40) NOT NULL,
    region_id NUMBER NOT NULL,
    flight_type VARCHAR2(3) NOT NULL CHECK (flight_type IN ('DOM', 'INT')),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT chk_airport_iata CHECK (REGEXP_LIKE(iata_code, '^[A-Z]{3}$')),
    CONSTRAINT fk_airport_region FOREIGN KEY (region_id) REFERENCES REGION(region_id)
);

-- 9. 게이트 (GATE)
CREATE TABLE GATE (
    gate_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport_id NUMBER NOT NULL,
    gate_code VARCHAR2(10) NOT NULL,
    gate_area_id NUMBER NOT NULL,
    flight_type VARCHAR2(3) NOT NULL CHECK (flight_type IN ('DOM', 'INT')),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT uq_gate_airport_code UNIQUE (airport_id, gate_code),
    CONSTRAINT fk_gate_airport FOREIGN KEY (airport_id) REFERENCES AIRPORT(airport_id),
    CONSTRAINT fk_gate_area FOREIGN KEY (gate_area_id) REFERENCES GATE_AREA(gate_area_id)
);

-- 10. 노선 (ROUTE)
CREATE TABLE ROUTE (
    route_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_airport_id NUMBER NOT NULL,
    arrival_airport_id NUMBER NOT NULL,
    flight_type VARCHAR2(3) NOT NULL CHECK (flight_type IN ('DOM', 'INT')),
    route_type_id NUMBER NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT fk_route_dept_airport FOREIGN KEY (departure_airport_id) REFERENCES AIRPORT(airport_id),
    CONSTRAINT fk_route_arrv_airport FOREIGN KEY (arrival_airport_id) REFERENCES AIRPORT(airport_id),
    CONSTRAINT fk_route_type FOREIGN KEY (route_type_id) REFERENCES ROUTE_TYPE(route_type_id),
    CONSTRAINT chk_route_airports CHECK (departure_airport_id != arrival_airport_id)
);

-- 11. 항공기 (AIRCRAFT)
CREATE TABLE AIRCRAFT (
    aircraft_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reg_no VARCHAR2(20) NOT NULL UNIQUE,
    model_name VARCHAR2(50) NOT NULL,
    total_seats NUMBER(4) NOT NULL CHECK (total_seats >= 1),
    status_name VARCHAR2(50) DEFAULT '운항가능' NOT NULL CHECK (status_name IN ('운항가능', '정비중', '퇴역')),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N'))
);

-- 12. 좌석 (SEAT)
CREATE TABLE SEAT (
    seat_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aircraft_id NUMBER NOT NULL,
    seat_no VARCHAR2(5) NOT NULL,
    seat_class_id NUMBER NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT uq_seat_aircraft_no UNIQUE (aircraft_id, seat_no),
    CONSTRAINT fk_seat_aircraft FOREIGN KEY (aircraft_id) REFERENCES AIRCRAFT(aircraft_id),
    CONSTRAINT fk_seat_class FOREIGN KEY (seat_class_id) REFERENCES SEAT_CLASS(seat_class_id)
);

-- 13. 운임 (FARE)
CREATE TABLE FARE (
    fare_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id NUMBER NOT NULL,
    seat_class_id NUMBER NOT NULL,
    season_id NUMBER NOT NULL,
    price NUMBER(10) NOT NULL CHECK (price > 0),
    is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT fk_fare_route FOREIGN KEY (route_id) REFERENCES ROUTE(route_id),
    CONSTRAINT fk_fare_seat_class FOREIGN KEY (seat_class_id) REFERENCES SEAT_CLASS(seat_class_id),
    CONSTRAINT fk_fare_season FOREIGN KEY (season_id) REFERENCES SEASON(season_id),
    CONSTRAINT uq_fare_rule UNIQUE (route_id, seat_class_id, season_id)
);

-- 14. 운항 스케줄 (FLIGHT)
CREATE TABLE FLIGHT (
    flight_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_no VARCHAR2(10) NOT NULL,
    route_id NUMBER NOT NULL,
    aircraft_id NUMBER NOT NULL,
    departure_gate_id NUMBER,
    arrival_gate_id NUMBER,
    departure_time TIMESTAMP NOT NULL,
    arrival_time TIMESTAMP NOT NULL,
    flight_status VARCHAR2(15) DEFAULT 'SCHEDULED' NOT NULL 
        CHECK (flight_status IN ('SCHEDULED', 'BOARDING', 'DEPARTED', 'ARRIVED', 'DELAYED', 'CANCELLED', 'COMPLETED')),
    delay_minutes NUMBER(5),
    is_deleted CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_deleted IN ('Y', 'N')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uq_flight_no_date UNIQUE (flight_no, departure_time),
    CONSTRAINT chk_flight_times CHECK (arrival_time > departure_time),
    CONSTRAINT chk_flight_delay CHECK (delay_minutes >= 0),
    CONSTRAINT fk_flight_route FOREIGN KEY (route_id) REFERENCES ROUTE(route_id),
    CONSTRAINT fk_flight_aircraft FOREIGN KEY (aircraft_id) REFERENCES AIRCRAFT(aircraft_id),
    CONSTRAINT fk_flight_dept_gate FOREIGN KEY (departure_gate_id) REFERENCES GATE(gate_id),
    CONSTRAINT fk_flight_arrv_gate FOREIGN KEY (arrival_gate_id) REFERENCES GATE(gate_id)
);

-- 15. 항공편 운임 (FLIGHT_FARE)
CREATE TABLE FLIGHT_FARE (
    flight_fare_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id NUMBER NOT NULL,
    seat_class_id NUMBER NOT NULL,
    fare_id NUMBER NOT NULL,
    price NUMBER(10) NOT NULL CHECK (price > 0),
    CONSTRAINT uq_flight_fare_class UNIQUE (flight_id, seat_class_id),
    CONSTRAINT fk_flight_fare_flight FOREIGN KEY (flight_id) REFERENCES FLIGHT(flight_id),
    CONSTRAINT fk_flight_fare_class FOREIGN KEY (seat_class_id) REFERENCES SEAT_CLASS(seat_class_id),
    CONSTRAINT fk_flight_fare_id FOREIGN KEY (fare_id) REFERENCES FARE(fare_id)
);

-- 16. 지연/결항 안내 (FLIGHT_NOTICE)
CREATE TABLE FLIGHT_NOTICE (
    flight_notice_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id NUMBER NOT NULL,
    notice_type VARCHAR2(10) NOT NULL CHECK (notice_type IN ('DELAY', 'CANCEL')),
    reason VARCHAR2(500) NOT NULL,
    delay_minutes NUMBER(5),
    created_by NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_flight_notice_flight FOREIGN KEY (flight_id) REFERENCES FLIGHT(flight_id),
    CONSTRAINT fk_flight_notice_maker FOREIGN KEY (created_by) REFERENCES MEMBER(member_id)
);

