-- 26. 관심 노선 (FAVORITE_ROUTE)
CREATE TABLE FAVORITE_ROUTE (
    favorite_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id NUMBER NOT NULL,
    favorite_type VARCHAR2(10) NOT NULL CHECK (favorite_type IN ('ROUTE', 'FLIGHT')),
    departure_airport_id NUMBER,
    arrival_airport_id NUMBER,
    flight_id NUMBER,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_favorite_combination UNIQUE (member_id, departure_airport_id, arrival_airport_id, flight_id),
    CONSTRAINT fk_fav_member FOREIGN KEY (member_id) REFERENCES MEMBER(member_id),
    CONSTRAINT fk_fav_dept_airport FOREIGN KEY (departure_airport_id) REFERENCES AIRPORT(airport_id),
    CONSTRAINT fk_fav_arrv_airport FOREIGN KEY (arrival_airport_id) REFERENCES AIRPORT(airport_id),
    CONSTRAINT fk_fav_flight FOREIGN KEY (flight_id) REFERENCES FLIGHT(flight_id),
    CONSTRAINT chk_favorite_type_data CHECK (
        (favorite_type = 'ROUTE' AND departure_airport_id IS NOT NULL AND arrival_airport_id IS NOT NULL AND flight_id IS NULL) OR
        (favorite_type = 'FLIGHT' AND flight_id IS NOT NULL AND departure_airport_id IS NULL AND arrival_airport_id IS NULL)
    )
);

